function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function getMorningDhikr(): HadithDhikr {
  return { text: pickRandom(ADHKAR_MORNING), source: 'أذكار الصباح', type: 'dhikr' };
}

export function getEveningDhikr(): HadithDhikr {
  return { text: pickRandom(ADHKAR_EVENING), source: 'أذكار المساء', type: 'dhikr' };
}

export function getAfterPrayerDhikr(): HadithDhikr {
  return { text: pickRandom(ADHKAR_AFTER_PRAYER), source: 'أذكار بعد الصلاة', type: 'dhikr' };
}

export function getDailyHadith(): HadithDhikr {
  return { text: pickRandom(AHADITH), source: 'حديث نبوي شريف', type: 'hadith' };
}

export function getRandomDhikr(): HadithDhikr {
  const pool = [...ADHKAR_MORNING, ...ADHKAR_EVENING, ...ADHKAR_AFTER_PRAYER, ...AHADITH];
  const types: HadithDhikr['type'][] = ['hadith', 'dhikr'];
  const t = pickRandom(types);
  return {
    text: pickRandom(pool),
    source: t === 'hadith' ? 'حديث نبوي شريف' : 'ذكر',
    type: t,
  };
}
